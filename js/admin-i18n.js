  var lang = localStorage.getItem("site_lang") || "my";

  function t(key) {
    var l = dict[lang] || {};
    if (l[key] != null) return l[key];
    if (dict.ms[key] != null) return dict.ms[key];
    return key;
  }

  function setLang(l) {
    lang = l;
    localStorage.setItem("site_lang", l);
  }

  function apply() {
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var k = el.getAttribute("data-i18n");
      var v = t(k);
      if (el.hasAttribute("data-i18n-html")) el.innerHTML = v;
      else el.textContent = v;
      if (el.hasAttribute("data-text")) el.setAttribute("data-text", v);
    });
    document.querySelectorAll(".lang-btn").forEach(function (b) {
      b.classList.toggle("active", b.getAttribute("data-lang") === lang);
    });
  }

  document.documentElement.lang = lang === "my" ? "ms" : "en";

  document.querySelectorAll(".lang-btn").forEach(function (b) {
    b.addEventListener("click", function () {
      setLang(b.getAttribute("data-lang"));
      localStorage.setItem("site_lang", lang);
      location.reload();
    });
  });

  window.adminI18n = { t: t, apply: apply, lang: function () { return lang; } };
  apply();
